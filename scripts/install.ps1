<#
.SYNOPSIS
    Install llama-cpp-server-explorer on Windows.

.DESCRIPTION
    Downloads a tarball of the `main` branch (no .git history), extracts to
    the install directory, then runs `pnpm install` and `pnpm build`.
    Re-run to update.

.PARAMETER InstallDir
    Target directory. Defaults to "$env:LOCALAPPDATA\llama-cpp-server-explorer".

.PARAMETER Branch
    Git branch to download. Default: main.

.EXAMPLE
    iwr -useb https://raw.githubusercontent.com/AlienResidents/llama-cpp-server-explorer/main/scripts/install.ps1 | iex

.EXAMPLE
    .\install.ps1 -InstallDir "C:\opt\llama-explorer"
#>

[CmdletBinding()]
param(
    [string]$InstallDir = "$env:LOCALAPPDATA\llama-cpp-server-explorer",
    [string]$Branch = "main"
)

$ErrorActionPreference = "Stop"

$RepoOwner = "AlienResidents"
$RepoName = "llama-cpp-server-explorer"
$TarballUrl = "https://github.com/$RepoOwner/$RepoName/archive/refs/heads/$Branch.tar.gz"

Write-Host "==> Installing to: $InstallDir"

# ─── Pre-flight: required tools ────────────────────────────────────────────

function Require-Command {
    param([string]$Name, [string]$Hint)
    if (-not (Get-Command $Name -ErrorAction SilentlyContinue)) {
        Write-Error "'$Name' is required but not on PATH. $Hint"
    }
}
Require-Command "tar"  "Standard on Windows 10 1803+. If missing, install Git for Windows or use Windows Subsystem for Linux."
Require-Command "node" "Install Node.js 22.12+ from https://nodejs.org/ or via nvm-windows."
Require-Command "pnpm" "Install via 'corepack enable && corepack prepare pnpm@latest --activate' or 'npm i -g pnpm'."

# ─── Fetch + extract into a staging dir ──────────────────────────────────────
#
# We extract the tarball into a temp staging dir first, then robocopy /MIR it
# into the install dir. /MIR deletes files in the destination that no longer
# exist in the source — a bare tar -xzf only adds/overwrites; it never deletes,
# so files removed from the repo between releases would linger and break the
# build (e.g. server/src/bedrock.ts after the multi-LLM refactor). We exclude
# data/ (the SQLite cache), node_modules/ (regenerated by pnpm install), and
# .git/ (in case the install dir is a dev clone).

if (-not (Test-Path $InstallDir)) {
    New-Item -Path $InstallDir -ItemType Directory -Force | Out-Null
}

$TmpTar = Join-Path ([System.IO.Path]::GetTempPath()) ("llama-explorer-" + [Guid]::NewGuid().ToString("N").Substring(0,8) + ".tar.gz")
$TmpStage = Join-Path ([System.IO.Path]::GetTempPath()) ("llama-explorer-stage-" + [Guid]::NewGuid().ToString("N").Substring(0,8))

try {
    Write-Host "==> Downloading $TarballUrl"
    Invoke-WebRequest -Uri $TarballUrl -OutFile $TmpTar -UseBasicParsing -TimeoutSec 60

    New-Item -Path $TmpStage -ItemType Directory -Force | Out-Null

    Write-Host "==> Extracting into staging dir"
    # --strip-components=1 drops the GitHub-injected top-level dir
    # (e.g. llama-cpp-server-explorer-main\).
    tar -xzf $TmpTar -C $TmpStage
    if ($LASTEXITCODE -ne 0) {
        throw "tar extraction failed (exit $LASTEXITCODE)"
    }

    # Tarball contains a single top-level dir. Find it.
    $Staged = (Get-ChildItem -Path $TmpStage -Directory | Select-Object -First 1).FullName
    if (-not $Staged) {
        throw "tarball did not produce an expected top-level directory"
    }

    Write-Host "==> Syncing into $InstallDir"
    # robocopy /MIR mirrors source → dest, deleting dest files not in source.
    # /XD excludes directories by name. /XF would exclude files (not needed).
    # robocopy exit codes 0-7 are success; 8+ are failures.
    robocopy $Staged $InstallDir /MIR /XD data node_modules .git /NFL /NDL /NJH /NJS
    if ($LASTEXITCODE -ge 8) {
        throw "robocopy sync failed (exit $LASTEXITCODE)"
    }
} finally {
    Remove-Item $TmpTar -ErrorAction SilentlyContinue
    Remove-Item $TmpStage -Recurse -Force -ErrorAction SilentlyContinue
}

# ─── Build ────────────────────────────────────────────────────────────────

Push-Location $InstallDir
try {
    Write-Host "==> pnpm install"
    pnpm install --frozen-lockfile
    if ($LASTEXITCODE -ne 0) { throw "pnpm install failed" }

    Write-Host "==> pnpm build"
    pnpm build
    if ($LASTEXITCODE -ne 0) { throw "pnpm build failed" }
} finally {
    Pop-Location
}

# ─── Done ─────────────────────────────────────────────────────────────────

Write-Host ""
Write-Host "✓ Installed to: $InstallDir"
Write-Host ""
Write-Host "Run with:"
Write-Host "    Set-Location `"$InstallDir`""
Write-Host "    pnpm start"
Write-Host ""
Write-Host "Then open http://localhost:8787 in your browser."
Write-Host ""
Write-Host "Re-run this script to update — the install dir is synced in place,"
Write-Host "your cache (data\explorer.db) is preserved."
